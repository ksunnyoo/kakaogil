def render_detail(p: dict, maxlen: int = 950) -> str:
    """절차 상세 말풍선 문구. 카카오 simpleText 1000자 제한 안으로 만든다."""
    lines = [
        p["title"],
        "",
        "바로 할 행동\n" + p["action"],
        "",
        "기한\n" + p["deadline"],
        "",
        "주의\n" + p["risk"],
        "",
        "담당 기관\n" + p["agency"],
    ]
    links = p.get("links") or []
    if links:
        lines += ["", "공식 링크"] + [f"· {label}: {url}" for label, url in links]
    if p.get("extra"):
        lines += ["", p["extra"]]
    lines += ["", VERIFY_NOTE]
    text = "\n".join(lines)
    return text
